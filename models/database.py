def init_db(app):
    """
    Initializes database tables safely and idempotently without dropping existing data.
    Seeds initial curated educational courses if catalogue is empty.

    VIVA EXPLANATION:
    Called on server startup (`app.py`).
    Uses `db.create_all()` which inspects SQLite and creates tables only if they don't already exist.
    Then calls `seed_courses_if_needed()` to ensure the course catalog is pre-populated.
    """
    db.init_app(app)
    with app.app_context():
        db.create_all()
        logger.info("Database tables initialized successfully.")
        
        # Seed course catalogue if empty
        try:
            from models.seed_data import seed_courses_if_needed
            seed_courses_if_needed()
        except Exception as e:
            logger.warning("Could not run course seeding: %s", e)

