"""
models/database.py
==================
MODULE PURPOSE (VIVA SUMMARY):
This file defines all relational database tables, SQLAlchemy ORM models, relationships,
and database initialization logic for the AetherLearn Personalized Learning Platform.

KEY CONCEPTS TO EXPLAIN IN VIVA:
1. What is an ORM (Object-Relational Mapping)?
   SQLAlchemy allows us to interact with SQLite (or PostgreSQL) using Python classes
   instead of raw SQL strings. A Python class represents a database table, and each
   class instance represents a single row.
2. SQLite with WAL Mode:
   The database runs SQLite with WAL (Write-Ahead Logging) mode and busy timeouts (configured in `app.py`).
   This allows concurrent read operations without locking the database file.
3. Multi-User Isolation:
   Every student record (video sessions, quiz attempts, skill scores, learning paths)
   has a foreign key (`user_id = db.Column(db.Integer, db.ForeignKey('users.id'))`).
   This guarantees that User A cannot see or tamper with User B's study progress.
4. Cascading Deletes:
   If a user account is deleted, SQLAlchemy's `cascade="all, delete-orphan"` automatically
   removes all related profiles, sessions, quiz attempts, and learning paths cleanly.

DATABASE ENTITIES & RELATIONSHIPS:
- User (1) -------- (1) UserProfile
- User (1) -------- (N) VideoLearningSession
- User (1) -------- (N) Quiz -------- (N) QuizQuestion
- User (1) -------- (N) QuizAttempt -------- (N) QuizResponse
- User (1) -------- (N) UserSkill
- User (1) -------- (N) UserCourse (linking to Course)
- User (1) -------- (N) LearningPath -------- (N) LearningMilestone
"""

from datetime import datetime
import json
import logging
from flask_sqlalchemy import SQLAlchemy

logger = logging.getLogger("models.database")

# Global SQLAlchemy database handle initialized in app.py
db = SQLAlchemy()


class User(db.Model):
    """
    User Account Model.

    VIVA EXPLANATION:
    Stores the core authentication and identity data for registered students.
    Passwords are never stored in plain text — they are securely hashed using
    pbkdf2:sha256/scrypt before being saved to `password_hash`.

    Relationships:
      - profile: One-to-One link with UserProfile (onboarding details).
      - video_sessions: One-to-Many link with VideoLearningSession (videos studied).
      - quizzes: One-to-Many link with Quiz (quizzes generated by or for this user).
      - quiz_attempts: One-to-Many link with QuizAttempt (test submissions & scores).
      - skills: One-to-Many link with UserSkill (estimated mastery per topic).
      - courses: One-to-Many link with UserCourse (course enrollments).
      - learning_paths: One-to-Many link with LearningPath (milestone roadmaps).
    """
    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    full_name = db.Column(db.String(120), nullable=False)
    email = db.Column(db.String(150), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    account_status = db.Column(db.String(30), default="active")  # 'active', 'suspended', 'inactive'
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # Relationships with cascading deletes (cleaning up orphans if user is removed)
    profile = db.relationship("UserProfile", backref="user", uselist=False, cascade="all, delete-orphan")
    video_sessions = db.relationship("VideoLearningSession", backref="user", lazy="dynamic", cascade="all, delete-orphan")
    quizzes = db.relationship("Quiz", backref="user", lazy="dynamic", cascade="all, delete-orphan")
    quiz_attempts = db.relationship("QuizAttempt", backref="user", lazy="dynamic", cascade="all, delete-orphan")
    skills = db.relationship("UserSkill", backref="user", lazy="dynamic", cascade="all, delete-orphan")
    courses = db.relationship("UserCourse", backref="user", lazy="dynamic", cascade="all, delete-orphan")
    learning_paths = db.relationship("LearningPath", backref="user", lazy="dynamic", cascade="all, delete-orphan")

    def __init__(self, **kwargs):
        super().__init__(**kwargs)

    def to_dict(self):
        """Serializes safe user attributes to dictionary (omits password_hash)."""
        return {
            "id": self.id,
            "full_name": self.full_name,
            "email": self.email,
            "account_status": self.account_status,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class UserProfile(db.Model):
    """
    User Learning Profile Model.

    VIVA EXPLANATION:
    Stores the student's preferences, academic background, and learning goals
    collected during the onboarding questionnaire (`/onboarding`).
    These values are heavily used by the recommendation engine and learning path generator
    to personalize study schedules and course recommendations.
    """
    __tablename__ = "user_profiles"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), unique=True, nullable=False, index=True)
    
    # Academic background
    education_level = db.Column(db.String(80), default="undergraduate")  # school, diploma, undergraduate, postgraduate, professional
    field_of_study = db.Column(db.String(150), default="")
    current_semester = db.Column(db.String(50), default="")
    
    # Serialized JSON lists / maps for flexible storage without extra join tables
    interests = db.Column(db.Text, default="[]")  # e.g. ["Python", "Machine Learning"]
    subject_skill_levels = db.Column(db.Text, default="{}")  # e.g. {"Python": "intermediate", "DSA": "beginner"}
    
    # Career & Study Goals
    primary_goal = db.Column(db.String(150), default="Learn a new technology")
    target_skill = db.Column(db.String(120), default="Python")
    target_completion_date = db.Column(db.String(50), default="")
    
    # Study habits & pacing budget
    daily_study_minutes = db.Column(db.Integer, default=45)
    weekly_study_hours = db.Column(db.Float, default=5.0)
    preferred_difficulty = db.Column(db.String(30), default="medium")  # easy, medium, hard, mixed
    preferred_format = db.Column(db.String(50), default="mixture")  # video, reading, practice questions, mixture
    career_goal = db.Column(db.String(150), default="")
    
    onboarding_completed = db.Column(db.Boolean, default=False)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    def __init__(self, **kwargs):
        super().__init__(**kwargs)

    def get_interests_list(self) -> list:
        """Helper to deserialize interests JSON string into a Python list."""
        try:
            return json.loads(self.interests) if self.interests else []
        except Exception:
            return []

    def set_interests_list(self, items: list):
        """Helper to serialize a Python list into the interests JSON text column."""
        self.interests = json.dumps(items or [])

    def get_skill_levels_dict(self) -> dict:
        """Helper to deserialize subject_skill_levels JSON string into a Python dict."""
        try:
            return json.loads(self.subject_skill_levels) if self.subject_skill_levels else {}
        except Exception:
            return {}

    def set_skill_levels_dict(self, levels: dict):
        """Helper to serialize a Python dict into the subject_skill_levels JSON text column."""
        self.subject_skill_levels = json.dumps(levels or {})

    def to_dict(self):
        """Serializes user profile to dictionary."""
        return {
            "user_id": self.user_id,
            "education_level": self.education_level,
            "field_of_study": self.field_of_study,
            "current_semester": self.current_semester,
            "interests": self.get_interests_list(),
            "subject_skill_levels": self.get_skill_levels_dict(),
            "primary_goal": self.primary_goal,
            "target_skill": self.target_skill,
            "target_completion_date": self.target_completion_date,
            "daily_study_minutes": self.daily_study_minutes,
            "weekly_study_hours": self.weekly_study_hours,
            "preferred_difficulty": self.preferred_difficulty,
            "preferred_format": self.preferred_format,
            "career_goal": self.career_goal,
            "onboarding_completed": self.onboarding_completed,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


